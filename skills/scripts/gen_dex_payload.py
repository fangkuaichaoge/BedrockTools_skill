#!/usr/bin/env python3
"""Turn a .dex into a C++ header so a native mod can embed it in .rodata.

Usage:
    python gen_dex_payload.py <classes.dex> <out_header.h> [--name dexBytes]

The generated header is `inline constexpr`, so it can be included from more than
one translation unit without ODR problems, and it lands in .rodata of the
resulting .so.

Why an array and not a file next to the mod: a preload-native mod's directory is
replaced on reinstall and may not be writable, so a side-car .dex is unreliable.
The array is read-only, needs no extraction, and is fed straight to
NewDirectByteBuffer at runtime (see references/embedding-dex-and-java-ui.md).
"""
import argparse
import struct
import sys
from pathlib import Path

DEX_MAGIC_PREFIX = b"dex\n"
DEX_HEADER_SIZE_OFF = 32


def c_array(name: str, blob: bytes, per_line: int = 16) -> str:
    rows = []
    for i in range(0, len(blob), per_line):
        chunk = blob[i:i + per_line]
        rows.append("    " + ", ".join(f"0x{b:02x}" for b in chunk) + ",")
    return f"inline constexpr unsigned char {name}[] = {{\n" + "\n".join(rows) + "\n};\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("dex")
    ap.add_argument("out")
    ap.add_argument("--name", default="dexBytes")
    ap.add_argument("--namespace", default="payload")
    args = ap.parse_args()

    dex_path = Path(args.dex)
    data = dex_path.read_bytes()

    # ---- validate: a silent offset/size error here costs an hour of runtime
    # debugging, because the failure surfaces as ClassNotFoundException.
    if not data.startswith(DEX_MAGIC_PREFIX):
        print(f"{dex_path}: missing dex magic {DEX_MAGIC_PREFIX!r}", file=sys.stderr)
        return 1
    if len(data) < 44:
        print(f"{dex_path}: too short to be a dex file", file=sys.stderr)
        return 1

    declared = struct.unpack_from("<I", data, DEX_HEADER_SIZE_OFF)[0]
    if declared != len(data):
        print(f"{dex_path}: header file_size {declared} != actual {len(data)} "
              f"(truncated or padded dex)", file=sys.stderr)
        return 1

    version = data[4:7].decode("ascii", "replace")

    header = (
        "// Auto-generated by gen_dex_payload.py - do not edit.\n"
        f"// source: {dex_path.name}  version: {version}  bytes: {len(data)}\n"
        "#pragma once\n\n"
        "#include <cstddef>\n\n"
        f"namespace {args.namespace} {{\n\n"
        f"// Feed to NewDirectByteBuffer(ptr, size); the array is read-only .rodata.\n"
        + c_array(args.name, data)
        + f"\ninline constexpr std::size_t {args.name}Size = {len(data)};\n\n"
        f"}} // namespace {args.namespace}\n"
    )

    out_path = Path(args.out)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(header, encoding="utf-8")

    print(f"wrote {out_path} ({len(data)} bytes, dex {version}, "
          f"~{len(header) // 6} source lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
